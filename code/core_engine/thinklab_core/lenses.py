def default_reading(question: str) -> str:
    return (
        "这不是一个等待标准答案的问题，而是一种正在发生的生活处境。我们先不急着把它归类，"
        "而是借三种不同的目光，看看其中有哪些部分被忽略了。"
    )


def reading_for(question: str) -> str:
    for keywords, text in READING_RULES:
        if any(keyword in question for keyword in keywords):
            return text
    return default_reading(question)


def get_lens(key: str) -> LensProfile:
    return LENS_PROFILES.get(key, LENS_PROFILES["stoic"])
